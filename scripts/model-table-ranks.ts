// Prints the ranks behind the model tables in ~/.claude/playbooks/plans-and-models.md, from the bundled data.
// Method: aggregateMaster over the merged data, each cell's entry.source_rank. Run:
//   node --import tsx scripts/model-table-ranks.ts            (markdown tables)
//   node --import tsx scripts/model-table-ranks.ts --names RE  (list master row names matching RE)
import { readFile } from "node:fs/promises";
import type { Dataset } from "../src/lib/contract";
import { mergeBriefcaseComponents, type BriefcaseComponentsSource } from "../src/lib/aa-briefcase";
import { mergeBriefcaseRubricRefresh, type BriefcaseRubricRefreshSource } from "../src/lib/aa-briefcase-rubric-refresh";
import { mergeAaModelProfileOverlays, type AaModelProfileOverlay } from "../src/lib/aa-model-profile-overlays";
import { aggregateMaster } from "../src/lib/master";
import { getIntelligenceIndexTaskCostMap } from "../src/lib/intelligence-index-costs";
import { getModelSpeedMap } from "../src/lib/model-speed";

const read = async (path: string) => JSON.parse(await readFile(path, "utf8"));
const merged = mergeBriefcaseRubricRefresh(
  mergeAaModelProfileOverlays(
    mergeBriefcaseComponents(await read("data/leaderboards.json") as Dataset, await read("data/aa-briefcase-components.json") as BriefcaseComponentsSource),
    await read("data/aa-model-profile-overlays.json") as AaModelProfileOverlay),
  await read("data/aa-briefcase-rubric-refresh.json") as BriefcaseRubricRefreshSource);
const { rows } = aggregateMaster(merged.evaluations, merged.entries, getIntelligenceIndexTaskCostMap(), getModelSpeedMap());

const namesArg = process.argv.indexOf("--names");
if (namesArg > 0) {
  const re = new RegExp(process.argv[namesArg + 1], "i");
  for (const r of rows) if (re.test(r.model)) console.log(r.model);
  process.exit(0);
}

const cols = [
  ["Terminal Bench", "terminal-bench-4-0"],
  ["Presentation", "aa-briefcase-presentation-elo"],
  ["Analytical Elo", "aa-briefcase-analytical-quality-elo"],
  ["Strategy & Ops", "strategy-ops-index"],
  ["Finance", "finance-accounting"],
  ["Omniscience", "aa-omniscience-index"],
  ["FrontierCode", "frontiercode-2-0"],
  ["Rubric", "aa-briefcase-rubric-score"],
  ["Briefcase", "briefcase-v1-1"],
  ["Economics", "economics-index"],
  ["Intelligence Index", "intelligence-index"],
] as const;

type Pair = [label: string, masterName: string];
const claude = (m: string, e: string) => `Claude ${m.includes(" ") ? m : `${m} 5.5`} (Adaptive Reasoning, ${e} Effort, Default Fallback)`;
const efforts = ["Max", "Xhigh", "High", "Medium", "Low"];
const groups: [string, Pair[]][] = [
  ["Claude", ["Opus", "Sonnet", "Haiku"].flatMap(m => efforts.map((e): Pair => [`${m} 5.5 ${e === "Xhigh" ? "xHigh" : e}`, claude(m, e)]))],
  ["Fable", [...[...efforts].reverse().map((e): Pair => [`Fable 5.2 ${e === "Xhigh" ? "xHigh" : e}`, claude("Fable 5.2", e)]), ["Fable 5.1 High", claude("Fable 5.1", "High")], ["Fable 5.1 Max", claude("Fable 5.1", "Max")]]],
  ["GPT", efforts.flatMap(e => [["Astra", "GPT-6 Astra"], ["Sol", "GPT-6.1 Sol"], ["Terra", "GPT-6.1 Terra"]].map(([s, n]): Pair => [`${s} ${e === "Xhigh" ? "xHigh" : e}`, `${n} (${e})`]))],
  ["Free", [
    ["DeepSeek V4.1 Flash 1017 Max", "DeepSeek V4.1 Flash 1017 (Max)"], ["DeepSeek V4.1 Flash 1017 High", "DeepSeek V4.1 Flash 1017 (High)"],
    ["DeepSeek V4.1 Flash 1017 Non-reasoning", "DeepSeek V4.1 Flash 1017 (Non-reasoning)"], ["DeepSeek V4.1 Flash Max", "DeepSeek V4.1 Flash (Max)"],
    ["DeepSeek V4.1 Flash Non-reasoning", "DeepSeek V4.1 Flash (Non-reasoning)"],
    ["GLM 5.3 Max", "GLM-5.3 (Max)"], ["GLM 5.3 Low", "GLM-5.3 (Low)"], ["GLM 5.3 Flash", "GLM-5.3-Flash"]]],
  ["Hydrogen", ["Xhigh", "High", "Medium", "Low"].map((e): Pair => [`Gemini 4 Hydrogen ${e === "Xhigh" ? "xHigh" : e}`, `Gemini 4 Hydrogen (${e})`])],
];

const byName = new Map(rows.map(r => [r.model, r]));
const fmt = (n: number) => Number.isInteger(n) ? String(n) : n.toFixed(Math.abs(n) >= 100 ? 0 : Math.abs(n) >= 10 ? 1 : 2);
const counts = cols.map(([label, id]) => `${label} ${rows.filter(r => r.cells[id]?.entry).length}`);
const capture = [...new Set(merged.evaluations.map(e => e.captured_at?.slice(0, 10)).filter(Boolean))].join(", ");

const out: string[] = [];
out.push(`# Model table ranks (AA capture ${capture})`, "",
  "Generated by `node --import tsx scripts/model-table-ranks.ts > docs/model-table-ranks-<date>.md` from the bundled data:",
  "`aggregateMaster` over the merged evaluations, each cell `cells[evalId].entry.source_rank` (the score in the second set",
  "of tables). Cost is the Intelligence Index cost per task; Time / task (minutes) and First answer (seconds) come from",
  "`data/aa-model-speed.json`. A dash means no value.", "",
  `Master rows: ${rows.length}. Rows per evaluation: ${counts.join(", ")}.`, "");
const header = `| Row | Master row | Cost / task | ${cols.map(c => c[0]).join(" | ")} | Time / task (min) | First answer (s) |`;
const sep = `|${"---|".repeat(cols.length + 5)}`;
for (const kind of ["Ranks", "Scores"] as const) {
  for (const [group, list] of groups) {
    out.push(`## ${group}: ${kind.toLowerCase()}`, "", header, sep);
    for (const [label, name] of list) {
      const r = byName.get(name);
      if (!r) { out.push(`| ${label} | ${name} (no master row) |${" — |".repeat(cols.length + 3)}`); continue; }
      const cells = cols.map(([, id]) => {
        const e = r.cells[id]?.entry;
        return e ? (kind === "Ranks" ? String(e.source_rank) : fmt(e.score_value as number)) : "—";
      });
      const c = r.intelligence_index_cost?.cost_usd, t = r.speed?.time_per_task_s, f = r.speed?.first_answer_s;
      out.push(`| ${label} | ${name} | ${c != null ? `$${c.toFixed(2)}` : "—"} | ${cells.join(" | ")} | ${t != null ? (t / 60).toFixed(1) : "—"} | ${f != null ? f.toFixed(1) : "—"} |`);
    }
    out.push("");
  }
}
console.log(out.join("\n"));
